-- =====================================================
-- Email — идентичность единого IdP (auth-service), makeup его не хранит.
--
-- Раньше makeup держал локальную копию email, и при привязке аккаунта по
-- username она не обновлялась — профиль показывал устаревший email, отличный
-- от того, которым пользователь входит. Теперь email в makeup отсутствует:
-- профиль берёт его из auth-service (/auth/me), поэтому расхождение невозможно.
-- =====================================================

-- Уникальное ограничение uk_users_email удалится вместе с колонкой.
ALTER TABLE users DROP COLUMN IF EXISTS email;
